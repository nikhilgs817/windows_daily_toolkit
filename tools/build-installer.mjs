import {createHash} from 'node:crypto';
import {copyFileSync,existsSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {zipSync} from 'fflate';
import {ROOT} from './common.mjs';
const manifest=JSON.parse(readFileSync(join(ROOT,'plugins/dailyops/com.dailyops.v2.sdPlugin/manifest.json'),'utf8'));
const packageFile=join(ROOT,'dist/com.dailyops.v2.streamDeckPlugin');
if(!existsSync(packageFile))throw Error('Run npm run build and npm run pack first.');
const version=manifest.Version;
const script=readFileSync(join(ROOT,'installer/Install-WindowsDailyToolkit.ps1'),'utf8');
if(!script.includes("$script:ReleaseVersion = '"+version+"'"))throw Error('Installer and plugin versions must match.');
if(!script.includes("/releases/download/v"+version.split('.').slice(0,3).join('.')+"'"))throw Error('Installer download URL must match the release version.');
const bundle=join(ROOT,'dist/WindowsDailyToolkit-Installer');mkdirSync(join(bundle,'installer'),{recursive:true});
copyFileSync(join(ROOT,'Install-WindowsDailyToolkit.cmd'),join(bundle,'Install-WindowsDailyToolkit.cmd'));
copyFileSync(join(ROOT,'installer/Install-WindowsDailyToolkit.ps1'),join(bundle,'installer/Install-WindowsDailyToolkit.ps1'));
copyFileSync(packageFile,join(bundle,'com.dailyops.v2.streamDeckPlugin'));
copyFileSync(join(ROOT,'docs/INSTALL.md'),join(bundle,'READ-ME-FIRST.txt'));
const metadata={PluginId:manifest.UUID,Version:version,File:'com.dailyops.v2.streamDeckPlugin',Sha256:createHash('sha256').update(readFileSync(packageFile)).digest('hex')};
for(const destination of [join(bundle,'installer-manifest.json'),join(ROOT,'dist/installer-manifest.json')])writeFileSync(destination,JSON.stringify(metadata,null,2)+'\n');
const files={};
for(const file of ['Install-WindowsDailyToolkit.cmd','installer/Install-WindowsDailyToolkit.ps1','com.dailyops.v2.streamDeckPlugin','installer-manifest.json','READ-ME-FIRST.txt'])files['WindowsDailyToolkit-Installer/'+file]=readFileSync(join(bundle,file));
writeFileSync(join(ROOT,'dist/WindowsDailyToolkit-Installer-'+version+'.zip'),zipSync(files,{level:9}));
console.log('Built ready-to-install ZIP, verified-payload manifest and double-click launcher for '+version);
